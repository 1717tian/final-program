DB_ENV_PATH = PROJECT_ROOT / ".env"

DB_ENV_KEYS = [
    "DB_HOST",
    "DB_PORT",
    "DB_NAME",
    "DB_USER",
    "DB_PASSWORD",
]

DEFAULT_DB_CONFIG = {
    "DB_HOST": "localhost",
    "DB_PORT": "5432",
    "DB_NAME": "db1",
    "DB_USER": "postgres",
    "DB_PASSWORD": "",
}


def read_env_file(path: Path) -> dict:
    """读取项目根目录 .env 中的数据库配置。"""

    config = dict(DEFAULT_DB_CONFIG)

    if not path.exists():
        return config

    try:
        for raw_line in path.read_text(encoding="utf-8").splitlines():
            line = raw_line.strip()

            if not line or line.startswith("#") or "=" not in line:
                continue

            key, value = line.split("=", 1)
            key = key.strip()
            value = value.strip().strip('"').strip("'")

            if key in DB_ENV_KEYS:
                config[key] = value
    except Exception:
        pass

    return config


def write_db_env_file(path: Path, config: dict):
    """把数据库配置写入 .env，同时尽量保留 .env 中的其他配置项。"""

    preserved_lines = []

    if path.exists():
        try:
            for raw_line in path.read_text(encoding="utf-8").splitlines():
                stripped = raw_line.strip()

                if not stripped or stripped.startswith("#") or "=" not in stripped:
                    preserved_lines.append(raw_line)
                    continue

                key = stripped.split("=", 1)[0].strip()

                if key not in DB_ENV_KEYS:
                    preserved_lines.append(raw_line)
        except Exception:
            preserved_lines = []

    db_lines = [
        "",
        "# Database config generated by PM2.5 launcher",
        f"DB_HOST={config.get('DB_HOST', '')}",
        f"DB_PORT={config.get('DB_PORT', '')}",
        f"DB_NAME={config.get('DB_NAME', '')}",
        f"DB_USER={config.get('DB_USER', '')}",
        f"DB_PASSWORD={config.get('DB_PASSWORD', '')}",
    ]

    content = "\n".join(preserved_lines + db_lines).strip() + "\n"
    path.write_text(content, encoding="utf-8")


def is_port_open(host: str, port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.5)

        try:
            return sock.connect_ex((host, port)) == 0
        except Exception:
            return False


def wait_for_port(host: str, port: int, timeout: int = 30) -> bool:
    start_time = time.time()

    while time.time() - start_time < timeout:
        if is_port_open(host, port):
            return True

        time.sleep(0.4)

    return False


def get_python_command() -> str:
    """
    优先使用项目内 .venv1 的 Python。
    打包成 exe 后，不能用 sys.executable 启动后端，因为 sys.executable 会变成启动器自身。
    """

    venv_python = PROJECT_ROOT / ".venv1" / "Scripts" / "python.exe"

    if venv_python.exists():
        return str(venv_python)

    python_cmd = shutil.which("python")

    if python_cmd:
        return python_cmd

    if not is_frozen():
        return sys.executable

    raise RuntimeError(
        "未找到 Python 解释器。\n\n"
        "建议在项目根目录保留虚拟环境：\n"
        ".venv1\\Scripts\\python.exe\n\n"
        "或者把 Python 加入系统 PATH。"
    )


def get_npm_command() -> str:
    if is_windows():
        npm_cmd = shutil.which("npm.cmd")
    else:
        npm_cmd = shutil.which("npm")

    if not npm_cmd:
        raise RuntimeError(
            "未找到 npm。\n\n"
            "请先安装 Node.js，并确认 npm 已加入系统 PATH。"
        )

    return npm_cmd


def taskkill_pid(pid: int):
    if not is_windows():
        return

    subprocess.run(
        ["taskkill", "/PID", str(pid), "/T", "/F"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        check=False,
    )


class ServiceProcess:
    def __init__(self, name, port, url):
        self.name = name
        self.port = port
        self.url = url
        self.process = None
        self.external_running = False

    @property
    def pid(self):
        if self.process and self.process.poll() is None:
            return self.process.pid

        return None

    @property
    def running(self):
        if self.process and self.process.poll() is None:
            return True

        if self.external_running and is_port_open("127.0.0.1", self.port):
            return True

        return False


