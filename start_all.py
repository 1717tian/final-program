    def get_database_config(self) -> dict:
        config = {
            "DB_HOST": self.db_host_var.get().strip(),
            "DB_PORT": self.db_port_var.get().strip(),
            "DB_NAME": self.db_name_var.get().strip(),
            "DB_USER": self.db_user_var.get().strip(),
            "DB_PASSWORD": self.db_password_var.get(),
        }

        missing = [key for key in ["DB_HOST", "DB_PORT", "DB_NAME", "DB_USER"] if not config[key]]

        if missing:
            raise ValueError("数据库配置缺少必填项：" + ", ".join(missing))

        try:
            port = int(config["DB_PORT"])
        except Exception:
            raise ValueError("数据库端口必须是数字，例如 5432")

        if port <= 0 or port > 65535:
            raise ValueError("数据库端口必须在 1 到 65535 之间")

        return config

    def apply_database_env(self, env: dict) -> dict:
        config = self.get_database_config()

        for key, value in config.items():
            env[key] = str(value)

        return env

