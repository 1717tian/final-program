    def _stream_output(self, process, prefix, tag):
        if not process.stdout:
            return

        for line in iter(process.stdout.readline, ""):
            if not line:
                break

            self.log_raw(f"[{prefix}] {line}", tag)

        code = process.poll()

        if code is not None:
            self.log(f"{prefix}进程已退出，退出码：{code}", "WARN")

