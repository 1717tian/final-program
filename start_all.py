def is_windows() -> bool:
    return os.name == "nt"


def is_frozen() -> bool:
    return getattr(sys, "frozen", False)


def get_app_base_dir() -> Path:
    """
    获取启动器所在目录。

    普通运行：
        使用 start_all.py 所在目录

    打包为 exe：
        使用 exe 所在目录

    注意：
        打包后建议把 exe 放在项目根目录，也就是 backend 和 frontend 的同级目录。
    """

    if is_frozen():
        return Path(sys.executable).resolve().parent

    return Path(__file__).resolve().parent


def find_project_root() -> Path:
    """
    自动寻找项目根目录。

    支持：
    1. start_all.py 放项目根目录
    2. start_all.py 放 scripts 目录
    3. 打包后的 exe 放项目根目录
    """

    start_dir = get_app_base_dir()

    candidates = [start_dir, *start_dir.parents]

    for path in candidates:
        if (path / "backend").exists() and (path / "frontend").exists():
            return path

    raise RuntimeError(
        "未找到项目根目录。\n\n"
        "请确认启动器位于项目目录内，并且项目目录下存在：\n"
        "backend/ 和 frontend/ 两个文件夹。"
    )


